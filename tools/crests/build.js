/* R94-01: node tools/crests/build.js writes the charge library into js/visualIdentity.js (between the CREST-CHARGES markers).
   The game never loads the tools; it only reads the finished path strings. */
"use strict";
const fs=require("fs"),path=require("path");
const C=require("./charges.js");
const file=path.join(__dirname,"..","..","js","visualIdentity.js");
const out={};
for(const name of Object.keys(C).sort()){const c=C[name]();out[name]=[c.body,c.detail||"",c.w||1.4,c.cut||"",c.wc||0];}
const body="const CREST_CHARGES = Object.freeze({\n"+Object.entries(out).map(([k,v])=>`    ${k}: ${JSON.stringify(v)}`).join(",\n")+"\n});\n";
const src=fs.readFileSync(file,"utf8"),a="/* CREST-CHARGES:BEGIN (generated by tools/crests/build.js; edit tools/crests/charges.js, not this block) */\n",b="/* CREST-CHARGES:END */";
const i=src.indexOf(a),j=src.indexOf(b);
if(i<0||j<0)throw new Error("markers missing in js/visualIdentity.js");
fs.writeFileSync(file,src.slice(0,i+a.length)+body+src.slice(j));
console.log("charges:",Object.keys(out).length,"bytes:",body.length);
