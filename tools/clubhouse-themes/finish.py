def H(t): return f'html[data-clubhouse="{t}"]{W}'
def rule(t, sels, body):
    sels = [s.strip() for s in sels.split(",") if s.strip()] if isinstance(sels, str) else sels
    plain, pseudo = [x for x in sels if "::" not in x], [x for x in sels if "::" in x]   # a pseudo-element is never valid inside :is()
    out = f"{H(t)} :is({', '.join(plain)}) {{ {body} }}\n" if plain else ""
    if pseudo: out += ",\n".join(f"{H(t)} {x}" for x in pseudo) + f" {{ {body} }}\n"
    return out

