def block():
    out = [START, "\n/* r100 B7 (Nik 2026-11-24, picks 13:13 UTC): each clubhouse has its own UI finish. Silver: smoked graphite panels,\n"
           "   platinum frames, gold only where it means something (main button, winner, totals). Metallic Black: polished black\n"
           "   steel panels, thin sharp gold. Premium Matte Black: neutral graphite velvet, satin titanium hairlines, satin graphite main button,\n"
           "   cool ivory titles, nothing glints. Colour and finish only; Wooden matches none of this. */\n"]
    for t, L in LOOK.items():
        out.append(f"\n/* ---- {t} ---- */\n")
        out.append(f"{H(t)} {{{L['tokens']}\n}}\n")
        out.append(rule(t, PANELS, L["panel"]))
        out.append(rule(t, CARDS, L["card"]))
        out.append(f"{H(t)} #app #mainMenu.v10Home {{ {L['tilebevel']} }}\n" if L["tilebevel"] else "")
        out.append(rule(t, ["#app #mainMenu.v10Home .fifaMenuGrid > .menuTile:not(#continueCareer)"], L["tile"]))
        out.append(rule(t, ["#app #mainMenu.v10Home .fifaMenuGrid > .menuTile:not(#continueCareer)::before"], L["tilelight"]))
        if L["bevel"]: out.append(rule(t, BEVELS, L["bevel"]))
        if L["second"]: out.append(rule(t, SECOND, L["second"]))
        if L["chrome"]: out.append(rule(t, CHROME, L["chrome"]))
        # The re-metalling filter replaces the hover/press brightness the screen sheets set (filter is one property), so a
        # pressed second button would give no feedback. Chain the same feedback on top of the clubhouse filter.
        for group, key in ((SECOND, "second"), (CHROME, "chrome")):
            f = re.search(r"filter:\s*([^;]+);", L[key] or "")
            if not f: continue
            hov = [g + ":hover:not(:disabled)" for g in group]
            act = [g + ":active:not(:disabled)" for g in group]
            out.append(rule(t, hov, f"filter: {f.group(1)} brightness(1.08);"))
            out.append(rule(t, act, f"filter: {f.group(1)} brightness(.88);"))
        if L["title"]: out.append(rule(t, TITLES, L["title"]))
        if L["label"]: out.append(rule(t, LABELS, L["label"]))
        if L.get("wall"): out.append(rule(t, WALLTEXT, L["wall"]))
        if L.get("navon"): out.append(rule(t, [".sd-nav-tab.isActive", ".sd-nav-tab.isActive > span", ".sd-nav-tab[aria-current=\"page\"]"], L["navon"]))
        if L.get("gold"): out.append(f"{H(t)} :is({', '.join(GOLD)}) {{ {GOLD_TOKENS} }}\n")
        if L.get("primary"):
            out.append(rule(t, PRIMARY, L["primary"]))
            out.append(rule(t, [p + "::after" for p in PRIMARY] + [p + "::before" for p in PRIMARY], "opacity: 0 !important; animation: none !important;"))
    out.append(END)
    return "".join(out)

