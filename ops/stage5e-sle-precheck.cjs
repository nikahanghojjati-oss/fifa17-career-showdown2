const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const write=(p,v)=>fs.writeFileSync(path.join(root,p),v);
const rollingPath='project-documents/START_NEXT_SESSION.md';
let rolling=read(rollingPath);
const marker='# CURRENT SOURCE CANDIDATE — v1.9.0 / 1.9.0-r1\n';
if(!rolling.startsWith(marker))rolling=marker+'\nStage 5E Private Remote Joining is the current source candidate. Production-proven recovery remains v1.8.1 / 1.8.1-r5 until merge and deploy. Fixed RJR remains 87/100 pending genuine production capability evidence.\n\n'+rolling;
write(rollingPath,rolling);
const contractPath='tests/contracts/sle-handoff-packaging-contracts.cjs';
let contract=read(contractPath);
const old='assert.equal(capsule.runtime.productionRuntimeRevision, sourceRevision, "Transition package must leave exact source/runtime identity on restored production r5.");';
const replacement='assert.notEqual(capsule.runtime.productionRuntimeRevision, sourceRevision, "A release candidate must remain distinct from the previous production-proven runtime until deployment.");\nassert.equal(sourceRevision, "1.9.0-r1", "Stage 5E source candidate runtime must be explicit.");';
if(!contract.includes(old))throw new Error('SLE source/production assertion marker not found.');
contract=contract.replace(old,replacement);
write(contractPath,contract);
fs.unlinkSync(__filename);
