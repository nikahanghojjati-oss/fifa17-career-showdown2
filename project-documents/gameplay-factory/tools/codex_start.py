#!/usr/bin/env python3
"""Start one Codex job on its PR, exactly once (Team G lead, 2026-10-17).

Nik's rules after the JOB-1843 pilot started three tasks: one start per job, one job at a time, "@codex" only in the single
trigger comment. This refuses to post when any of those would break.

  python3 tools/codex_start.py 1844 --pr 885 [--repo /path/to/clone]

Refuses when:
  - the job fails tools/check_job.py;
  - the PR is closed, or its title doesn't start with JOB-<n>;
  - "@codex" already appears in the PR body (that alone starts a task);
  - the job already had a start, unless this is an allowed retry (--retry): the earlier run must have replied (failed or
    blocked) at least RETRY_WAITS[n] ago (10 min before the 2nd start, 1 hour before the 3rd), and a job never gets more
    than three starts (Nik 2026-10-17 00:48-00:49 UTC: retry without his OK when it makes sense, a third start only
    after a reasonable time, never two runs of one job at once);
  - another open JOB- PR got a Codex start with no Codex reply after it yet (one job at a time);
  - the budget for the current 5-hour Codex window is used up (ledger below), or Codex is paused after a limit message.

Budget (Nik 2026-10-17: "understand its limit, don't overuse it"): every start is written to the ledger
/mnt/project-files/gameplay/factory/codex_ledger.json with its weight (1 = short job, 2 = long run such as CE2PG 5/10
seasons or the meter). At most WINDOW_BUDGET weight per rolling 5 hours, so a full day spreads over the resets.
When Codex answers "usage limit", run with --pause-until <ISO time> (the reset shown in Codex) and nothing starts before then.
"""
import datetime
import argparse, json, pathlib, subprocess, sys

REPO = "repos/nikahanghojjati-oss/fifa17-career-showdown2"
CODEX = "chatgpt-codex-connector[bot]"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
LEDGER = pathlib.Path("/mnt/project-files/gameplay/factory/codex_ledger.json")
WINDOW = datetime.timedelta(hours=5)
WINDOW_BUDGET = 3
RETRY_WAITS = {1: datetime.timedelta(minutes=10), 2: datetime.timedelta(hours=1)}


def now():
    return datetime.datetime.now(datetime.timezone.utc)


def load_ledger():
    try:
        return json.loads(LEDGER.read_text())
    except (OSError, ValueError):
        return {"starts": [], "pausedUntil": None}


def gh(*args):
    r = subprocess.run(["gh", "api", *args], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"gh api {' '.join(args)} failed: {r.stderr.strip()}")
    return json.loads(r.stdout) if r.stdout.strip() else None


def comments(pr):
    return gh(f"{REPO}/issues/{pr}/comments?per_page=100")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("job", type=int)
    ap.add_argument("--pr", type=int, required=True)
    ap.add_argument("--repo", default="/home/claude/repo")
    ap.add_argument("--retry", action="store_true", help="the one retry after a genuine failure reply")
    ap.add_argument("--weight", type=int, default=1, help="2 for long runs (CE2PG 5/10 seasons, meter)")
    ap.add_argument("--pause-until", help="record a Codex limit: no starts before this ISO time, then exit")
    a = ap.parse_args()
    ledger = load_ledger()
    if a.pause_until:
        ledger["pausedUntil"] = a.pause_until
        LEDGER.write_text(json.dumps(ledger, indent=1))
        sys.exit(f"Codex paused until {a.pause_until}")
    if ledger.get("pausedUntil") and now() < datetime.datetime.fromisoformat(ledger["pausedUntil"]):
        sys.exit(f"REFUSED: Codex hit its limit; paused until {ledger['pausedUntil']}")
    used = sum(x["weight"] for x in ledger["starts"] if now() - datetime.datetime.fromisoformat(x["at"]) < WINDOW)
    if used + a.weight > WINDOW_BUDGET:
        sys.exit(f"REFUSED: {used} of {WINDOW_BUDGET} Codex budget used in the last 5 hours; wait for the window to roll")
    check = pathlib.Path(__file__).with_name("check_job.py")
    if subprocess.run([sys.executable, str(check), str(a.job), "--repo", a.repo]).returncode:
        sys.exit("REFUSED: the job file fails its preflight")
    pr = gh(f"{REPO}/pulls/{a.pr}")
    if pr["state"] != "open" or not pr["title"].startswith(f"JOB-{a.job}"):
        sys.exit(f"REFUSED: PR #{a.pr} is {pr['state']} or not titled JOB-{a.job}")
    if "@codex" in (pr.get("body") or ""):
        sys.exit("REFUSED: the PR body mentions @codex, which already starts a task; remove it first")
    cs = comments(a.pr)
    starts = [c for c in cs if "@codex" in (c.get("body") or "") and c["user"]["login"] != CODEX]
    if starts:
        if not a.retry:
            sys.exit(f"REFUSED: PR #{a.pr} already had a Codex start; pass --retry only after a genuine failure")
        if len(starts) >= 3:
            sys.exit(f"REFUSED: JOB-{a.job} already had three starts. Move it to Claude helpers")
        replies = [c for c in cs if c["user"]["login"] == CODEX and c["created_at"] > starts[-1]["created_at"]
                   and "Codex Review" not in (c.get("body") or "")]
        if not replies:
            sys.exit("REFUSED: the first run hasn't replied yet; never retry a running job")
        age = now() - datetime.datetime.fromisoformat(replies[-1]["created_at"].replace("Z", "+00:00"))
        wait = RETRY_WAITS[len(starts)]
        if age < wait:
            sys.exit(f"REFUSED: wait {int((wait - age).total_seconds() // 60) + 1} more minutes after the failure before this retry")
    for other in gh(f"{REPO}/pulls?state=open&per_page=100"):
        if other["number"] == a.pr or not other["title"].startswith("JOB-"):
            continue
        cs = comments(other["number"])
        starts = [i for i, c in enumerate(cs) if "@codex" in (c.get("body") or "") and c["user"]["login"] != CODEX]
        if starts and not any(c["user"]["login"] == CODEX and "Summary" in (c.get("body") or "") for c in cs[starts[-1] + 1:]):
            sys.exit(f"REFUSED: Codex is still on PR #{other['number']}; one job at a time")
    body = (f"@codex Do git fetch origin factory/gameplay-v1, read git show FETCH_HEAD:project-documents/gameplay-factory/"
            f"jobs/JOB-{a.job}.md, and do exactly what it says. Work on this PR's branch, {pr['head']['ref']}.{FOOTER}")
    c = gh("-X", "POST", f"{REPO}/issues/{a.pr}/comments", "-f", f"body={body}")
    ledger["starts"].append({"job": a.job, "pr": a.pr, "at": now().isoformat(timespec="seconds"), "weight": a.weight, "comment": c["id"]})
    LEDGER.write_text(json.dumps(ledger, indent=1))
    print(f"started JOB-{a.job} on PR #{a.pr}: comment {c['id']} (budget {used + a.weight}/{WINDOW_BUDGET} this window)")


if __name__ == "__main__":
    main()
