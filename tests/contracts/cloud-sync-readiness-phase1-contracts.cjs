const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const source=fs.readFileSync("js/cloudSyncRevisionModel.js","utf8");
const phase=fs.readFileSync("CLOUD_SYNC_READINESS_PHASE_1.md","utf8");
const roadmap=fs.readFileSync("REMOTE_JOINING_EXECUTION_ROADMAP.md","utf8");
const versioning=fs.readFileSync("VERSIONING_POLICY.md","utf8");
const shell=fs.readFileSync("index.html","utf8");
const optional=fs.readFileSync("js/optionalModules.js","utf8");
assert.doesNotMatch(source,/\blocalStorage\b/);
assert.doesNotMatch(source,/\bfetch\s*\(|XMLHttpRequest|WebSocket/);
assert.doesNotMatch(shell,/cloudSyncRevisionModel\.js/);
assert.doesNotMatch(optional,/cloudSyncRevisionModel\.js/);
assert.match(phase,/no backend, no account system, no remote writes, no Remote Joining runtime/i);
assert.match(roadmap,/Cloud \/ Sync Readiness[\s\S]+Private Account[\s\S]+Connected Rivalry[\s\S]+Remote Joining/i);
assert.match(versioning,/PATCH[\s\S]+MINOR[\s\S]+MAJOR/i);
const window={};window.window=window;
vm.runInContext(source,vm.createContext({window,console,JSON,Object,Array,String,Number,Boolean}),{filename:"js/cloudSyncRevisionModel.js"});
const m=window.CareerModeSyncRevisionModel;
const seed=m.createAuthority({accountId:"acct_1",objectType:"save",objectId:"save_1"});
assert.equal(seed.ok,true);
const put=(deviceId,baseRevision,idempotencyKey,contentHash,score)=>({operation:"put",accountId:"acct_1",objectType:"save",objectId:"save_1",deviceId,baseRevision,idempotencyKey,contentHash,content:{score}});
const first=m.applyMutation(seed.state,seed.ledger,put("device_a",0,"key_1","hash_a",3));
assert.equal(first.status,"accepted");assert.equal(first.state.revision,1);
const replay=m.applyMutation(first.state,first.ledger,put("device_a",0,"key_1","hash_a",3));
assert.equal(replay.status,"replayed");assert.equal(replay.state.revision,1);
const stale=m.applyMutation(first.state,first.ledger,put("device_b",0,"key_2","hash_b",5));
assert.equal(stale.status,"conflict");assert.equal(stale.conflict.remoteRevision,1);
const deleted=m.applyMutation(first.state,first.ledger,{operation:"delete",accountId:"acct_1",objectType:"save",objectId:"save_1",deviceId:"device_a",baseRevision:1,idempotencyKey:"key_delete"});
assert.equal(deleted.state.tombstone,true);assert.equal(deleted.state.revision,2);
const staleWrite=m.applyMutation(deleted.state,deleted.ledger,put("device_b",1,"key_stale","hash_old",9));
assert.equal(staleWrite.status,"conflict");assert.equal(staleWrite.conflict.remoteTombstone,true);
const implicit=m.applyMutation(deleted.state,deleted.ledger,put("device_a",2,"key_put","hash_restore",7));
assert.equal(implicit.status,"tombstone-restore-required");
const restored=m.applyMutation(deleted.state,deleted.ledger,{operation:"restore",accountId:"acct_1",objectType:"save",objectId:"save_1",deviceId:"device_a",baseRevision:2,idempotencyKey:"key_restore",contentHash:"hash_restored",content:{score:7}});
assert.equal(restored.status,"accepted");assert.equal(restored.state.revision,3);assert.equal(restored.state.tombstone,false);
const mismatch=m.applyMutation(first.state,first.ledger,put("device_a",0,"key_1","hash_changed",4));
assert.equal(mismatch.status,"idempotency-conflict");
process.stdout.write("PASS Cloud/Sync Readiness Phase 1 deterministic sync model\n");
