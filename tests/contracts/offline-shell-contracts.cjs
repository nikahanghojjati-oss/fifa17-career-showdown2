const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=process.cwd();
const read=file=>fs.readFileSync(path.join(root,file),"utf8");
const exists=file=>fs.existsSync(path.join(root,file));
const html=read("index.html");
const app=read("js/app.js");
const controller=read("js/offlineApp.js");
const worker=read("service-worker.js");
const manifest=JSON.parse(read("manifest.webmanifest"));
const revision=html.match(/name="app-asset-revision" content="([^"]+)"/)?.[1];
assert.match(revision||"",/^\d+\.\d+\.\d+-r\d+$/);
assert.equal(manifest.start_url,"./");
assert.equal(manifest.scope,"./");
assert.equal(manifest.display,"standalone");
assert.equal(manifest.theme_color,"#20272d");
assert.ok(manifest.icons.some(icon=>icon.sizes==="192x192"));
assert.ok(manifest.icons.some(icon=>icon.sizes==="512x512"&&String(icon.purpose).includes("any")));
assert.ok(manifest.icons.some(icon=>icon.sizes==="512x512"&&String(icon.purpose).includes("maskable")));
for(const icon of manifest.icons){
 const url=new URL(icon.src,"https://example.test/");
 assert.equal(url.searchParams.get("v"),revision);
 const file=url.pathname.replace(/^\//,"");
 assert.ok(exists(file),`Missing install icon: ${file}`);
}
const eager=[...html.matchAll(/<script\s+defer\s+src="([^"]+)"/g)].map(match=>match[1]);
assert.equal(eager.length,7);
assert.equal(eager.some(src=>src.includes("offlineApp.js")),false);
assert.ok(app.includes("manifest.webmanifest"));
assert.ok(app.includes("js/offlineApp.js"));
assert.ok(worker.includes(`const RUNTIME_REVISION = "${revision}";`));
const shellMatch=worker.match(/const SHELL_PATHS = Object\.freeze\((\[[\s\S]*?\])\);/);
assert.ok(shellMatch,"Version-owned shell list is missing.");
const shellFiles=JSON.parse(shellMatch[1]);
assert.equal(shellFiles.length,new Set(shellFiles).size);
assert.ok(shellFiles.length>=50);
for(const file of shellFiles)assert.ok(exists(file),`Missing shell resource: ${file}`);
const installBlock=worker.slice(worker.indexOf('self.addEventListener("install"'),worker.indexOf('self.addEventListener("message"'));
assert.match(installBlock,/populateCurrentCache/);
assert.doesNotMatch(installBlock,/skipWaiting/);
const updateBlock=worker.slice(worker.indexOf("CMS_ACTIVATE_UPDATE"),worker.indexOf('self.addEventListener("activate"'));
assert.ok(updateBlock.indexOf("verifyCache(CACHE_NAME)")>=0);
assert.ok(updateBlock.indexOf("skipWaiting()")>updateBlock.indexOf("verifyCache(CACHE_NAME)"));
assert.match(worker,/request\.mode\s*===\s*"navigate"[\s\S]*versionedShellUrl\("index\.html"\)/);
assert.match(controller,/new Set\(\["mainMenu"\s*,\s*"dashboard"\]\)/);
assert.ok(controller.includes('data-transaction-busy="true"'));
assert.ok(controller.includes('data-critical-recovery="true"'));
assert.match(controller,/controllerchange[\s\S]*activationRequested[\s\S]*location\.reload\(\)/);
assert.match(controller,/updateViaCache\s*:\s*"none"/);
assert.ok(controller.includes("OFFLINE · LOCAL TRACKER READY"));
assert.ok(controller.includes("OFFLINE · YOUTUBE MEDIA REQUIRES A CONNECTION"));
process.stdout.write(`PASS  offline shell contracts: ${shellFiles.length} version-owned resources and guarded update activation\n`);
