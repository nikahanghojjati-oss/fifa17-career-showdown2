const assert=require('node:assert/strict');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
(async()=>{
  const graph=JSON.parse(fs.readFileSync('POS7_IMPACT_GRAPH.json','utf8'));
  const manifest=JSON.parse(fs.readFileSync('CURRENT_PRODUCT_TEST_MANIFEST.json','utf8'));
  const router=await import(pathToFileURL('scripts/pos7-impact-router.mjs'));
  const ownedIndexes=Object.values(graph.invariants).flatMap(inv=>inv.testIndexes||[]);
  assert.equal(ownedIndexes.length,manifest.tests.length);
  assert.equal(new Set(ownedIndexes).size,ownedIndexes.length,'Every deterministic blocking contract must have exactly one IMPACT-7 owner.');
  assert.deepEqual(new Set(ownedIndexes),new Set(manifest.tests.map((_,index)=>index)));
  const proofIds=Object.values(graph.proofBundles).flat();
  assert.equal(proofIds.length,45,'IMPACT-7 must expose all 45 exact proof IDs in this topology.');
  assert.equal(new Set(proofIds).size,proofIds.length,'Proof IDs must have exactly one bundle owner.');
  const doc=router.routeFiles(['README.md']);
  assert.equal(doc.profile,'DOC_ONLY'); assert.equal(doc.testCount,0); assert.equal(doc.proofCount,0);
  const ops=router.routeFiles(['NEXT_TASK.md','scripts/pos7-continuity.mjs']);
  assert.equal(ops.profile,'OPS_ONLY'); assert.equal(ops.operations,true); assert.equal(ops.testCount,0);
  const css=router.routeFiles(['css/app.css']);
  assert.equal(css.fullSeal,false); assert.ok(css.invariants.includes('VISUAL_PRESENTATION')); assert.ok(css.tests.includes('tests/contracts/shared-showdown-dual-full-screen-contracts.cjs'),'CSS impact must keep permanent dual full screen consumer proof.');
  assert.ok(css.proofs.includes('HOME_BOOTSTRAP_INLINE')); assert.ok(css.proofs.includes('V1_VISUAL_IMMERSION_INLINE'));
  assert.ok(!css.proofs.includes('STAGE3_PAIRING_EMULATOR'),'CSS-only impact must not select remote emulator proof.');
  const pairing=router.routeFiles(['js/stage4ConnectedRivalry.js']);
  assert.ok(pairing.invariants.includes('PAIRING_RIVALRY')); assert.ok(pairing.invariants.includes('REMOTE_JOINING')); assert.ok(pairing.invariants.includes('SHARED_SETUP'),'Transitive consumers must expand pairing -> remote joining -> shared setup.');
  assert.ok(pairing.proofs.includes('STAGE3_PAIRING_EMULATOR'));
  const auth=router.routeFiles(['js/stage5fProductionAuthenticatedNegatives.js']);
  assert.ok(auth.proofs.includes('STAGE5F_ACCOUNT_CHOOSER_CONTRACT')); assert.ok(auth.proofs.includes('STAGE5F_AUTH_NEGATIVES_CONTRACT'));
  const full=router.routeFiles(['package.json']);
  assert.equal(full.profile,'FULL_SEAL'); assert.equal(full.testCount,60); assert.equal(full.proofCount,45); assert.equal(full.operations,true);
  const unknown=router.routeFiles(['new-unknown-authority.bin']);
  assert.equal(unknown.profile,'FULL_SEAL'); assert.equal(unknown.testCount,60); assert.equal(unknown.proofCount,45);
  const forced=router.routeFiles(['README.md'],{forceFull:true});
  assert.equal(forced.profile,'FULL_SEAL'); assert.equal(forced.testCount,60);
  console.log('PASS IMPACT-7 router: exact ownership, transitive consumers, narrow known changes, and fail-closed full seal.');
})().catch(error=>{console.error(error);process.exitCode=1;});
