const assert = require("node:assert/strict");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
(async () => {
  const t = await import(pathToFileURL(path.resolve("scripts/pos5-transition.mjs")));
  const b = await import(pathToFileURL(path.resolve("scripts/build-recovery-beacon.mjs")));
  const d = await import(pathToFileURL(path.resolve("scripts/build-developer-relay-file.mjs")));
  const r = await import(pathToFileURL(path.resolve("scripts/pos5-risk-router.mjs")));
  const s = o => ({ ...t.emptySignals(), ...o });
  assert.equal(t.assessTransition(s({})).status, "CONTINUE");
  const warning = t.assessTransition(s({ usageWarning: true, atomicOperation: true, recoveryBeaconFresh: false }));
  assert.equal(warning.status, "TRANSFER");
  assert.equal(warning.finishOrAbortAtomicFirst, true);
  assert.equal(warning.generateDeveloperRelayFile, true);
  assert.equal(t.canCorrectSameHypothesis({ failedCorrections: 2, newEvidence: false }).allowed, false);
  assert.equal(t.canCorrectSameHypothesis({ failedCorrections: 2, newEvidence: true }).action, "REFRAME_WITH_NEW_EVIDENCE");
  const beacon = b.buildRecoveryBeacon({ repository: "owner/repo", branch: "ops/x", pr: 1, head: "a".repeat(40), lane: "POS5", failureClass: "TEST_DEFECT", rootHypothesis: "stale process gate", lastSafeCheckpoint: "safe", nextAction: "next", updatedAt: "2026-09-08T00:00:00Z" });
  const body = b.upsertRecoveryBeacon(b.upsertRecoveryBeacon("PR body", beacon), beacon);
  assert.equal((body.match(/POS5_RB2/g) || []).length, 2);
  const drf = d.buildDeveloperRelayFile({ generatedAt: "2026-09-08T00:00:00Z", repository: "owner/repo", branch: "ops/x", pr: 1, head: "a".repeat(40), lane: "SSJR Shared Setup", lastSafeCheckpoint: "safe", rootHypotheses: ["none"], nextAction: "verify live head", references: ["NEXT_TASK.md"] });
  assert.ok(Buffer.byteLength(drf, "utf8") <= d.maxBytes);
  assert.match(drf, /Developer Relay File DRF-1/);
  assert.match(drf, /orientation only/i);
  const ops = r.classifyChangedPaths(["PROJECT_OPERATING_SYSTEM_V5.md", "scripts/pos5-transition.mjs"]);
  assert.deepEqual(ops.domains, ["OPS_ONLY"]);
  assert.equal(ops.lane, "TARGETED");
  const security = r.classifyChangedPaths(["firestore.spark.rules"]);
  assert.ok(security.domains.includes("SECURITY_PROVIDER"));
  assert.equal(security.lane, "CANDIDATE");
  console.log("PASS POS v5 session operations: binary TD-1, hypothesis-bounded DLL-1, non-mutating RB-2, compact DRF-1 and risk-routed validation are coherent.");
})().catch(error => { console.error(error.stack || error); process.exit(1); });
