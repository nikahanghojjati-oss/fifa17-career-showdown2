const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const source=fs.readFileSync("js/offlineApp.js","utf8");
const match=source.match(/function setMenuMediaOfflineState\(offline\)\{[\s\S]*?\nfunction renderConnectivity/);
assert.ok(match,"Production offline-media function was not found.");
const fn=match[0].replace(/\nfunction renderConnectivity[\s\S]*$/,"");
const status={textContent:"YOUTUBE · PAUSED"};
const toggle={disabled:false,attrs:new Map(),setAttribute(k,v){this.attrs.set(k,String(v));},removeAttribute(k){this.attrs.delete(k);},click(){throw new Error("Unexpected media click");}};
const context=vm.createContext({console,document:{getElementById(id){return id==="menuMusicToggle"?toggle:id==="menuMusicStatus"?status:null;}},window:{isMenuMediaPlaying(){return false;}},menuMediaStatusBeforeOffline:""});
vm.runInContext(fn+"\nthis.runOffline=setMenuMediaOfflineState;",context);
context.runOffline(true);
assert.equal(status.textContent,"OFFLINE · YOUTUBE MEDIA REQUIRES A CONNECTION");
assert.equal(toggle.disabled,true);
context.runOffline(true);
context.runOffline(false);
assert.equal(status.textContent,"YOUTUBE · PAUSED","Repeated offline renders must preserve the true pre-offline media status.");
assert.equal(toggle.disabled,false,"Live reconnect must re-enable media.");
assert.equal(toggle.attrs.has("aria-disabled"),false,"Live reconnect must clear aria-disabled.");
console.log("PASS  v1.3 live offline-to-online media restoration contract.");
